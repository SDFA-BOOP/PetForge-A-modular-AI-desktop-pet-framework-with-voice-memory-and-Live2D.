def detect_emotion(text: str) -> str:
    """根据回复文本粗略判断情绪，用于驱动角色表情动画。"""
    if not text:
        return "neutral"
    for emotion, keywords in EMOTION_KEYWORDS.items():
        for kw in keywords:
            if kw in text:
                return emotion
    return "neutral"


