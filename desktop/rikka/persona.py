def detect_emotion_delta(text: str, cap: int = 3) -> int:
    """根据文本中的中二/平静关键词，返回自动情绪调整量（限制在 ±cap 内）。"""
    if not text:
        return 0
    up = sum(1 for kw in CHUNIBYO_KEYWORDS if kw in text)
    down = sum(1 for kw in CALM_KEYWORDS if kw in text)
    return max(-cap, min(cap, up - down))


